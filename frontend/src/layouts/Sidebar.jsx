export default function Sidebar() {
  const [backendStatus, setBackendStatus] = useState('checking'); // 'checking' | 'connected' | 'error'

  const checkBackend = () => {
    setBackendStatus('checking');
    api.get('/dashboard/stats')
      .then(() => setBackendStatus('connected'))
      .catch(() => setBackendStatus('error'));
  };

  useEffect(() => {
    checkBackend();
    const timer = setInterval(checkBackend, 15000);
    return () => clearInterval(timer);
  }, []);

  return (
    <aside className="fixed top-0 left-0 h-screen w-60 bg-navy flex flex-col z-50">
      {/* Logo */}
      <div className="px-5 py-5 border-b border-navy-light">
        <h1 className="text-white text-lg font-semibold tracking-tight">TIMORA</h1>
        <p className="text-slate-custom text-xs mt-0.5">Exam Scheduler</p>
      </div>

      {/* Navigation */}
      <nav className="flex-1 overflow-y-auto py-3 px-3">
        {navItems.map((item, i) => {
          if (item.divider) {
            return <hr key={`div-${i}`} className="my-2 border-navy-light" />;
          }
          return (
            <NavLink
              key={item.path}
              to={item.path}
              className={({ isActive }) =>
                `flex items-center gap-3 px-3 py-2 rounded text-sm transition-colors duration-150 ${
                  isActive
                    ? 'bg-steel text-white font-medium'
                    : 'text-gray-400 hover:text-white hover:bg-navy-light'
                }`
              }
            >
              <span className="flex-shrink-0">{iconMap[item.icon]}</span>
              <span>{item.label}</span>
            </NavLink>
          );
        })}
      </nav>

      {/* Footer & Backend Status */}
      <div className="px-4 py-3 border-t border-navy-light flex items-center justify-between text-xs">
        <div className="flex items-center gap-2">
          <span
            className={`w-2 h-2 rounded-full ${
              backendStatus === 'connected'
                ? 'bg-emerald-400 shadow-[0_0_8px_rgba(52,211,153,0.6)]'
                : backendStatus === 'checking'
                ? 'bg-amber-400 animate-pulse'
                : 'bg-rose-500'
            }`}
          />
          <span className="text-gray-300 font-mono text-[11px]">
            {backendStatus === 'connected'
              ? 'Backend Online'
              : backendStatus === 'checking'
              ? 'Connecting...'
              : 'Backend Offline'}
          </span>
        </div>
        {backendStatus === 'error' ? (
          <button
            onClick={checkBackend}
            className="text-[11px] text-amber-300 underline hover:text-amber-200"
          >
            Retry
          </button>
        ) : (
          <span className="text-gray-500 text-[10px]">v1.0.0</span>
        )}
      </div>
    </aside>
  );
}
